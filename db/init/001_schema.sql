CREATE TABLE app_user (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cf_handle TEXT NOT NULL UNIQUE,
    rating INTEGER CHECK (rating IS NULL OR rating >= 0),
    max_rating INTEGER CHECK (max_rating IS NULL OR max_rating >= 0),
    country TEXT,
    verified_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE contest (
    contest_id INTEGER PRIMARY KEY,
    name TEXT NOT NULL,
    contest_type TEXT,
    start_time TIMESTAMPTZ,
    duration_secs INTEGER CHECK (duration_secs IS NULL OR duration_secs >= 0)
);

CREATE TABLE problem (
    problem_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contest_id INTEGER NOT NULL REFERENCES contest(contest_id) ON DELETE RESTRICT,
    problem_index TEXT NOT NULL,
    name TEXT NOT NULL,
    rating INTEGER CHECK (rating IS NULL OR rating BETWEEN 800 AND 3500),
    solved_count INTEGER NOT NULL DEFAULT 0 CHECK (solved_count >= 0),
    UNIQUE (contest_id, problem_index)
);

CREATE TABLE tag (
    tag_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    category TEXT
);

CREATE TABLE problem_tag (
    problem_id BIGINT NOT NULL REFERENCES problem(problem_id) ON DELETE CASCADE,
    tag_id BIGINT NOT NULL REFERENCES tag(tag_id) ON DELETE RESTRICT,
    PRIMARY KEY (problem_id, tag_id)
);

CREATE TABLE submission (
    submission_id BIGINT PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(user_id) ON DELETE CASCADE,
    problem_id BIGINT NOT NULL REFERENCES problem(problem_id) ON DELETE RESTRICT,
    verdict TEXT NOT NULL CHECK (verdict IN (
        'FAILED', 'OK', 'PARTIAL', 'COMPILATION_ERROR', 'RUNTIME_ERROR',
        'WRONG_ANSWER', 'TIME_LIMIT_EXCEEDED',
        'MEMORY_LIMIT_EXCEEDED', 'IDLENESS_LIMIT_EXCEEDED',
        'SECURITY_VIOLATED', 'CRASHED', 'INPUT_PREPARATION_CRASHED',
        'CHALLENGED', 'SKIPPED', 'TESTING', 'REJECTED', 'SUBMITTED'
    )),
    language TEXT,
    submitted_at TIMESTAMPTZ NOT NULL,
    time_ms INTEGER CHECK (time_ms IS NULL OR time_ms >= 0),
    memory_kb INTEGER CHECK (memory_kb IS NULL OR memory_kb >= 0)
);

CREATE TABLE rating_change (
    user_id BIGINT NOT NULL REFERENCES app_user(user_id) ON DELETE CASCADE,
    contest_id INTEGER NOT NULL REFERENCES contest(contest_id) ON DELETE RESTRICT,
    old_rating INTEGER,
    new_rating INTEGER,
    rank_in_contest INTEGER CHECK (rank_in_contest IS NULL OR rank_in_contest > 0),
    PRIMARY KEY (user_id, contest_id)
);

CREATE TABLE user_tag_stat (
    user_id BIGINT NOT NULL REFERENCES app_user(user_id) ON DELETE CASCADE,
    tag_id BIGINT NOT NULL REFERENCES tag(tag_id) ON DELETE RESTRICT,
    attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    accepted INTEGER NOT NULL DEFAULT 0 CHECK (accepted >= 0),
    wrong_attempts INTEGER NOT NULL DEFAULT 0 CHECK (wrong_attempts >= 0),
    last_solved_at TIMESTAMPTZ,
    proficiency DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (proficiency BETWEEN 0 AND 1),
    PRIMARY KEY (user_id, tag_id),
    CHECK (accepted <= attempts),
    CHECK (wrong_attempts <= attempts)
);

CREATE TABLE recommendation (
    rec_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(user_id) ON DELETE CASCADE,
    problem_id BIGINT NOT NULL REFERENCES problem(problem_id) ON DELETE RESTRICT,
    mode TEXT NOT NULL CHECK (mode IN ('warm_up', 'stretch', 'fix_weaknesses')),
    hint_level SMALLINT NOT NULL DEFAULT 0 CHECK (hint_level BETWEEN 0 AND 3),
    score DOUBLE PRECISION NOT NULL CHECK (score BETWEEN 0 AND 1),
    reason JSONB NOT NULL DEFAULT '[]'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    clicked_at TIMESTAMPTZ,
    solved_at TIMESTAMPTZ
);

CREATE TABLE tag_prerequisite (
    tag_id BIGINT NOT NULL REFERENCES tag(tag_id) ON DELETE CASCADE,
    prereq_tag_id BIGINT NOT NULL REFERENCES tag(tag_id) ON DELETE CASCADE,
    PRIMARY KEY (tag_id, prereq_tag_id),
    CHECK (tag_id <> prereq_tag_id)
);

-- JSON array keeps the base schema compatible with stock PostgreSQL.
-- This can be migrated to pgvector when vector search is implemented.
CREATE TABLE problem_embedding (
    problem_id BIGINT PRIMARY KEY REFERENCES problem(problem_id) ON DELETE CASCADE,
    embedding JSONB NOT NULL CHECK (jsonb_typeof(embedding) = 'array')
);

CREATE INDEX submission_user_time_idx
    ON submission (user_id, submitted_at DESC);
CREATE INDEX submission_solved_user_problem_idx
    ON submission (user_id, problem_id)
    WHERE verdict = 'OK';
CREATE INDEX problem_rating_popularity_idx
    ON problem (rating, solved_count DESC);
CREATE INDEX problem_tag_tag_problem_idx
    ON problem_tag (tag_id, problem_id);
